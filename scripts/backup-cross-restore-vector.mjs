#!/usr/bin/env node
/**
 * Generate or verify `src/services/backup/__fixtures__/cross-restore.json`.
 *
 * Uses the same noble params as `src/services/backup/crypto.ts`:
 *   @noble/ciphers xchacha20poly1305(key32, nonce24, aadUtf8)
 *   AAD = pubky://{owner}/pub/hypercolor.app/v1/backup/latest
 *   recovery code = 32 bytes, base64url, no padding
 *   blob = { version: 1, algorithm: "XChaCha20Poly1305", nonceB64, ciphertextB64 }
 *
 * Mobile can ingest this file at the crypto/snapshot layer. One live staging
 * cross-restore still waits for P3 owner writes + P5 live proof.
 *
 *   node scripts/backup-cross-restore-vector.mjs          # verify checked-in vector
 *   node scripts/backup-cross-restore-vector.mjs --write  # regenerate vector
 */
import { xchacha20poly1305 } from "@noble/ciphers/chacha.js";
import { base64urlnopad } from "@scure/base";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ALGORITHM = "XChaCha20Poly1305";
const KEY_BYTES = 32;
const NONCE_BYTES = 24;
const PATH_SUFFIX = "/pub/hypercolor.app/v1/backup/latest";
const OWNER = "a".repeat(52);
const PEER = "z".repeat(52);

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fixturePath = join(
  root,
  "src/services/backup/__fixtures__/cross-restore.json",
);

function backupLatestUrl(owner) {
  return `pubky://${owner}${PATH_SUFFIX}`;
}

function snapshotFor(owner) {
  return {
    version: 1,
    ownerPubky: owner,
    exportedAt: 1_700_000_000_000,
    contacts: [
      {
        pubky: PEER,
        ownerPubky: owner,
        displayName: "Peer",
        trustScore: 0.5,
        isFollowing: true,
        isFollower: false,
        isMutual: false,
        addedManually: true,
        firstSeenAt: 10,
      },
    ],
    messageRequests: [],
    linkMessages: [],
    readCursors: [],
    groupChannels: [],
    groupMembers: [],
    groupMessages: [],
    paymentRequests: [],
    tipEndpoints: [],
    attachments: [],
  };
}

function seal(plaintext, key, nonce, aad) {
  return xchacha20poly1305(key, nonce, aad).encrypt(plaintext);
}

function open(sealed, key, nonce, aad) {
  return xchacha20poly1305(key, nonce, aad).decrypt(sealed);
}

function writeVector() {
  const owner = OWNER;
  const snapshot = snapshotFor(owner);
  const aad = backupLatestUrl(owner);
  const key = new Uint8Array(KEY_BYTES);
  const nonce = new Uint8Array(NONCE_BYTES);
  crypto.getRandomValues(key);
  crypto.getRandomValues(nonce);
  const plaintext = new TextEncoder().encode(JSON.stringify(snapshot));
  const sealed = seal(plaintext, key, nonce, new TextEncoder().encode(aad));
  const blob = {
    version: 1,
    algorithm: ALGORITHM,
    nonceB64: base64urlnopad.encode(nonce),
    ciphertextB64: base64urlnopad.encode(sealed),
  };
  const vector = {
    format: "hypercolor-owner-backup-cross-restore-v1",
    notes:
      "Ciphertext + recovery code for mobile↔web restore at the crypto/snapshot layer. Generated by scripts/backup-cross-restore-vector.mjs with @noble/ciphers xchacha20poly1305. A live staging homeserver round-trip is still a later P3/P5 proof.",
    aad,
    ownerPubky: owner,
    recoveryCode: base64urlnopad.encode(key),
    blob,
    blobJson: JSON.stringify(blob),
    snapshot,
    expected: {
      version: 1,
      ownerPubky: owner,
      exportedAt: 1_700_000_000_000,
      contactPubky: PEER,
      contactDisplayName: "Peer",
    },
  };
  mkdirSync(dirname(fixturePath), { recursive: true });
  writeFileSync(fixturePath, `${JSON.stringify(vector, null, 2)}\n`);
  return vector;
}

function verifyVector() {
  const vector = JSON.parse(readFileSync(fixturePath, "utf8"));
  if (vector.aad !== backupLatestUrl(vector.ownerPubky)) {
    throw new Error(`AAD mismatch: ${vector.aad}`);
  }
  if (vector.blob.algorithm !== ALGORITHM) {
    throw new Error(`algorithm mismatch: ${vector.blob.algorithm}`);
  }
  const key = base64urlnopad.decode(vector.recoveryCode);
  const nonce = base64urlnopad.decode(vector.blob.nonceB64);
  if (key.length !== KEY_BYTES || nonce.length !== NONCE_BYTES) {
    throw new Error("recovery code or nonce is the wrong length");
  }
  const opened = open(
    base64urlnopad.decode(vector.blob.ciphertextB64),
    key,
    nonce,
    new TextEncoder().encode(vector.aad),
  );
  const parsed = JSON.parse(new TextDecoder().decode(opened));
  if (parsed.ownerPubky !== vector.expected.ownerPubky) {
    throw new Error("decrypted owner mismatch");
  }
  if (parsed.contacts[0]?.displayName !== vector.expected.contactDisplayName) {
    throw new Error("decrypted contact mismatch");
  }
  if (vector.blobJson !== JSON.stringify(vector.blob)) {
    throw new Error("blobJson is not the exact JSON.stringify of blob");
  }
  return vector;
}

const write = process.argv.includes("--write");
const vector = write ? writeVector() : verifyVector();
console.log(
  write ? "wrote" : "verified",
  fixturePath,
  "\n  aad:",
  vector.aad,
  "\n  recoveryCode bytes:",
  KEY_BYTES,
  "\n  algorithm:",
  ALGORITHM,
);
